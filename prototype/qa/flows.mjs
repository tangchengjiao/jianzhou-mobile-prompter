import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { writeFile } from 'node:fs/promises';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1400, height: 1200 }, deviceScaleFactor: 1 });
const errors = [];
const checks = [];
page.on('pageerror', e => errors.push(e.message));
const check = (name) => { checks.push(name); console.log(`PASS ${name}`); };
const screen = page.getByTestId('device-screen');
try {
  await page.goto('http://127.0.0.1:4186');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('heading', { name: '这次，想讲什么？' }).waitFor();
  await page.waitForTimeout(350);
  await screen.screenshot({ path: 'qa/home-iphone.png' });
  const bounds = await screen.boundingBox();
  assert.equal(bounds.width, 393); assert.equal(bounds.height, 852);
  check('iPhone 393 × 852 viewport and selected home design');

  await page.getByRole('button', { name: '全屏练习', exact: true }).click();
  await page.getByRole('button', { name: '开始全屏练习', exact: true }).click();
  await page.getByRole('button', { name: '取消倒计时', exact: true }).click();
  await page.waitForTimeout(3300);
  assert.equal(await page.getByRole('button', { name: '播放提词', exact: true }).count(), 1);
  assert.match(await page.locator('.reading-label').innerText(), /已暂停/);
  await page.getByRole('button', { name: '返回', exact: true }).click();
  await page.getByRole('button', { name: '返回', exact: true }).click();
  await page.getByRole('button', { name: '悬浮提词', exact: true }).click();
  check('cancelled countdown does not start reading later');

  await page.getByLabel('稿件标题', { exact: true }).fill('见舟试拍稿');
  await page.getByLabel('稿件正文', { exact: true }).fill('今天，先把事情讲清楚。\n\n停一下，再接着往下讲。\n\n重读的时候，回到这一句。');
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('heading', { name: '按你的习惯来' }).waitFor();
  await page.waitForTimeout(450);
  assert.equal(await page.getByTestId('keyboard-dock').getAttribute('data-visible'), 'false');
  const font = page.getByRole('slider', { name: '字号', exact: true });
  await font.focus(); await font.press('End');
  assert.equal(await font.inputValue(), '48');
  await page.getByRole('button', { name: '关', exact: true }).click();
  await page.getByRole('switch', { name: '镜像文字' }).click();
  assert.equal(await page.getByRole('switch', { name: '镜像文字' }).getAttribute('aria-checked'), 'true');
  await page.waitForTimeout(300);
  await screen.screenshot({ path: 'qa/settings.png' });
  await page.getByRole('button', { name: '设置好了' }).click();
  await page.reload();
  assert.equal(await page.getByLabel('稿件标题', { exact: true }).inputValue(), '见舟试拍稿');
  assert.match(await page.getByLabel('稿件正文', { exact: true }).inputValue(), /回到这一句/);
  check('script edits and settings persist after reload');

  await page.getByRole('button', { name: '准备悬浮提词', exact: true }).click();
  await page.getByRole('heading', { name: '调到舒服，再开拍。' }).waitFor();
  assert.equal(await page.getByRole('slider', { name: '字号', exact: true }).inputValue(), '48');
  assert.match(await page.locator('.honest-note').innerText(), /原生版本真机验证/);
  await screen.screenshot({ path: 'qa/prepare.png' });
  await page.getByRole('button', { name: '先全屏练一遍' }).click();
  await page.getByRole('button', { name: '暂停提词', exact: true }).waitFor();
  await page.waitForTimeout(1400);
  const beforePause = await page.locator('.reading-label').innerText();
  await page.getByRole('button', { name: '暂停提词', exact: true }).click();
  assert.match(await page.locator('.reading-label').innerText(), /已暂停/);
  await page.waitForTimeout(500);
  assert.equal(await page.getByRole('button', { name: '播放提词', exact: true }).count(), 1);
  check('timed reading starts, advances and pauses');
  await page.getByRole('button', { name: '下一句', exact: true }).click();
  assert.match(await page.locator('.reading-line.is-current').innerText(), /停一下/);
  await page.getByRole('button', { name: '上一句', exact: true }).click();
  assert.match(await page.locator('.reading-line.is-current').innerText(), /今天/);
  await page.getByRole('button', { name: '重读的时候，回到这一句。', exact: true }).click();
  assert.match(await page.locator('.reading-line.is-current').innerText(), /重读/);
  await screen.screenshot({ path: 'qa/reading.png' });
  await page.getByRole('button', { name: '从头再来' }).click();
  assert.match(await page.locator('.reading-line.is-current').innerText(), /今天/);
  check('manual next, previous, sentence seek and reset');

  await page.getByRole('button', { name: '调整悬浮' }).click();
  await page.getByRole('button', { name: '演示悬浮提词', exact: true }).click();
  const handle = page.locator('.float-handle');
  const float = page.getByLabel('演示悬浮窗', { exact: true });
  const oldPos = await float.boundingBox();
  const hb = await handle.boundingBox();
  await page.mouse.move(hb.x + 50, hb.y + 15); await page.mouse.down();
  await page.mouse.move(hb.x + 85, hb.y + 75, { steps: 8 }); await page.mouse.up();
  const newPos = await float.boundingBox();
  assert.ok(newPos.y > oldPos.y + 30);
  await screen.screenshot({ path: 'qa/floating-demo.png' });
  await page.getByRole('button', { name: '关闭悬浮演示' }).click();
  await page.getByRole('button', { name: '返回', exact: true }).click();
  check('explicitly labelled in-screen floating demo drags and closes');

  await page.getByRole('button', { name: '从文件导入' }).click();
  await page.getByLabel('选择稿件文件').setInputFiles({ name: '中文导入.txt', mimeType: 'text/plain', buffer: Buffer.from('导入中文稿。\n\n第二段继续讲。', 'utf8') });
  await page.getByRole('button', { name: '导入这份稿子' }).click();
  assert.equal(await page.getByLabel('稿件标题', { exact: true }).inputValue(), '中文导入');
  assert.match(await page.getByLabel('稿件正文', { exact: true }).inputValue(), /第二段继续讲/);
  await page.getByRole('button', { name: '设置', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出当前稿件' }).click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), '中文导入.txt');
  await page.getByRole('button', { name: '设置好了' }).click();
  check('UTF-8 file import and TXT export');

  await page.getByLabel('稿件正文', { exact: true }).fill('');
  await page.locator('.jz-header').click({ position: { x: 100, y: 75 } });
  assert.equal(await page.getByRole('button', { name: '准备悬浮提词', exact: true }).isDisabled(), true);
  check('empty script cannot start');

  await page.getByTestId('device-picker').click();
  await page.getByRole('menuitemradio', { name: 'Pixel 10' }).click();
  await page.waitForTimeout(350);
  await screen.screenshot({ path: 'qa/home-android.png' });
  const android = await screen.boundingBox();
  assert.equal(android.width, 427); assert.equal(android.height, 952);
  check('Android device preview preserved at 427 × 952');
  assert.deepEqual(errors, []);
  check('no uncaught browser errors');
  await writeFile('qa/flow-results.json', JSON.stringify({ checks, errors, beforePause, iosViewport: bounds, androidViewport: android }, null, 2));
} finally { await browser.close(); }
